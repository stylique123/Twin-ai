// PANEL 14 ANSWERS (facts-only writer). Builds scripts/ops/fixtures/panel14-answers.json:
// for every panel request, each need the facts-only writer can raise, answered
// ONLY from facts already in that creator's fixture (fictional-panel.json), or
// "skip" when the fixture has nothing. Never writes new material.
//   node scripts/ops/panel14Answers.mjs            (writes the file)
//   node scripts/ops/panel14Answers.mjs --check    (fails if the file is stale)
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildSync } from 'esbuild'

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const OUT = join(REPO, 'scripts/ops/fixtures/panel14-answers.json')

async function load(name) {
  const target = join(REPO, 'scripts', 'ops', `.${name}.bundle.mjs`)
  buildSync({ entryPoints: [join(REPO, `packages/shared/src/script/${name}.ts`)], bundle: true, format: 'esm', platform: 'node', outfile: target, logLevel: 'silent' })
  return import(target)
}

/**
 * Pure: one creator + one request → { questionKey: answer | 'skip' }. Each need
 * the facts-only writer can raise (`needsFor`) is answered ONLY from that
 * creator's fixture facts that fit the request and the need, quoted as stored.
 */
export function answersFor(fo, gate, creator, request) {
  const prod = request.product ? creator.products.find((p) => p.key === request.product) : null
  const req = { note: request.note, goal: request.goal, product: prod ? { id: prod.key, name: prod.name } : null }
  const ledger = gate.buildLedger({
    knowledge: (creator.stories ?? []).map((s, i) => ({ id: `s${i}`, kind: s.kind, text: s.text })),
    answers: creator.answers ?? {},
    products: (creator.products ?? []).map((p) => ({ id: p.key, name: p.name, knowledge: p.facts })),
    targetProductId: prod?.key ?? null,
  })
  const items = fo.writerItems(ledger)
  const rel = fo.relevantItems(req, items, ledger)
  const pick = (kind) => {
    switch (kind) {
      case 'story': case 'proof': return rel.filter((it) => it.origin === 'her_story' || it.origin === 'her_answer')
      case 'number': return rel.filter((it) => /\d/.test(it.text))
      case 'product_fact': return rel.filter((it) => it.origin === 'product_fact')
      case 'steps': return rel.filter((it) => /\b(?:first|then|step|next|after)\b/i.test(it.text))
      case 'opinion': return items.filter((it) => it.opinion && rel.length)
      default: return []
    }
  }
  const out = {}
  for (const need of fo.needsFor(req)) {
    const ans = pick(need.kind).slice(0, 1).map((it) => it.text).join(' ').trim()
    out[need.key] = ans || 'skip'
  }
  return out
}

export async function build() {
  const fo = await load('factsOnly')
  const gate = await load('inventionGate')
  const fx = JSON.parse(readFileSync(join(REPO, 'scripts/ops/fixtures/fictional-panel.json'), 'utf8'))
  const byCreator = Object.fromEntries(fx.creators.map((c) => [c.key, c]))
  const requests = {}
  for (const r of fx.requests) {
    const c = byCreator[r.creator]
    if (!c) continue
    requests[r.id] = { creator: r.creator, note: r.note, answers: answersFor(fo, gate, c, r) }
  }
  return { _note: 'FICTIONAL. Panel 14 answers, generated by scripts/ops/panel14Answers.mjs ONLY from facts already in fictional-panel.json; "skip" where the fixture has nothing. Keys are the facts-only question keys (mn:fo:*; product keys stand in for product ids).', version: 2, requests }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const doc = await build()
  const text = JSON.stringify(doc, null, 1) + '\n'
  if (process.argv.includes('--check')) {
    const cur = (() => { try { return readFileSync(OUT, 'utf8') } catch { return '' } })()
    if (cur !== text) { console.error('panel14-answers.json is stale: run node scripts/ops/panel14Answers.mjs'); process.exit(1) }
    console.log('panel14-answers.json: fresh')
  } else {
    writeFileSync(OUT, text)
    const all = Object.values(doc.requests).flatMap((r) => Object.values(r.answers))
    console.log(`wrote ${Object.keys(doc.requests).length} requests, ${all.length} needs, ${all.filter((a) => a === 'skip').length} skip`)
  }
}
