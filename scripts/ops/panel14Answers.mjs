// PANEL 14 ANSWERS (facts-only writer). Builds scripts/ops/fixtures/panel14-answers.json:
// for every panel request, each need the facts-only writer can raise, answered
// ONLY from facts already in that creator's fixture (fictional-panel.json), or
// "skip" when the fixture has nothing. Never writes new material.
//   node scripts/ops/panel14Answers.mjs            (writes the file)
//   node scripts/ops/panel14Answers.mjs --check    (fails if the file is stale)
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildSync } from 'esbuild'

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const OUT = join(REPO, 'scripts/ops/fixtures/panel14-answers.json')

async function loadFactsOnly() {
  const target = join(REPO, 'scripts', 'ops', '.factsOnly.bundle.mjs')
  buildSync({ entryPoints: [join(REPO, 'packages/shared/src/script/factsOnly.ts')], bundle: true, format: 'esm', platform: 'node', outfile: target, logLevel: 'silent' })
  return import(target)
}

const PRICE = /\$\s?\d|\b\d+(?:\.\d+)?\s?(?:dollars|usd)\b/i
const SIZE = /\b\d+(?:\.\d+)?\s?(?:oz|ml|g|kg|cm|mm)\b/i

/** Pure: one creator + one request → { needKey: answer | 'skip' }. */
export function answersFor(fo, creator, request) {
  const prod = request.product ? creator.products.find((p) => p.key === request.product) : null
  const req = { note: request.note, goal: request.goal, kind: request.kind, product: prod ? { id: prod.key, name: prod.name } : null }
  // The creator's own material as a ledger (fixture only).
  const ledger = [
    ...(creator.stories ?? []).map((s, i) => ({ id: `s${i}`, kind: s.kind, text: s.text, source: 'material' })),
    ...Object.entries(creator.answers ?? {}).map(([k, v]) => ({ id: `a:${k}`, kind: k === 'story' ? 'experience' : k, text: String(v), source: 'material',
      // Her product line is the product's own fact when it names this product.
      ...(k === 'product_slot' && prod && String(v).toLowerCase().includes(prod.name.toLowerCase()) ? { product_id: prod.key } : {}) })),
    ...(creator.products ?? []).flatMap((p) => p.facts.map((f, j) => ({ id: `${p.key}:${j}`, kind: 'product_fact', text: f.value, source: 'material', product_id: p.key }))),
  ]
  const out = {}
  for (const need of fo.needsFor(req)) {
    const facts = fo.factsForNeed(need, req, ledger)
    let ans = facts.map((f) => f.text).join(' ')
    // A product need the ledger match missed can still be answered from her product line or a price/size fact.
    if (!ans && prod) {
      if (need.kind === 'price') ans = prod.facts.map((f) => f.value).find((v) => PRICE.test(v)) ?? ''
      else if (need.kind === 'size') ans = prod.facts.map((f) => f.value).find((v) => SIZE.test(v)) ?? ''
      else if (need.kind === 'product_name' || need.kind === 'usage') ans = String(creator.answers?.product_slot ?? '').toLowerCase().includes(prod.name.toLowerCase()) ? String(creator.answers.product_slot) : ''
    }
    out[need.key] = ans.trim() ? ans.trim() : 'skip'
  }
  return out
}

export async function build() {
  const fo = await loadFactsOnly()
  const fx = JSON.parse(readFileSync(join(REPO, 'scripts/ops/fixtures/fictional-panel.json'), 'utf8'))
  const byCreator = Object.fromEntries(fx.creators.map((c) => [c.key, c]))
  const requests = {}
  for (const r of fx.requests) {
    const c = byCreator[r.creator]
    if (!c) continue
    requests[r.id] = { creator: r.creator, note: r.note, answers: answersFor(fo, c, r) }
  }
  return { _note: 'FICTIONAL. Panel 14 answers, generated by scripts/ops/panel14Answers.mjs ONLY from facts already in fictional-panel.json; "skip" where the fixture has nothing. Keys are the facts-only need keys (product keys stand in for product ids).', version: 1, requests }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const doc = await build()
  const text = JSON.stringify(doc, null, 1) + '\n'
  if (process.argv.includes('--check')) {
    const cur = (() => { try { return readFileSync(OUT, 'utf8') } catch { return '' } })()
    if (cur !== text) { console.error('panel14-answers.json is stale: run node scripts/ops/panel14Answers.mjs'); process.exit(1) }
    console.log('panel14-answers.json: fresh')
  } else {
    writeFileSync(OUT, text)
    const all = Object.values(doc.requests).flatMap((r) => Object.values(r.answers))
    console.log(`wrote ${Object.keys(doc.requests).length} requests, ${all.length} needs, ${all.filter((a) => a === 'skip').length} skip`)
  }
}
