// THE REALISTIC PANEL MODE (plan v6.8 §34, owner 26 Oct night).
//
// Panels ran in `cost_mode: test`, which stubs the secondary stack (product and
// web-page extraction, the Reddit pain map, the practice viewers, outside and
// niche knowledge, audience vocabulary, niche notes), so they did not measure
// what production does. `cost_mode: full` switches that stack ON — for TEST AND
// PANEL ACCOUNTS ONLY — behind the guardrails below.
//
// ⚖️ REAL CREATORS ARE UNAFFECTED. Every decision here takes the account kind
// derived from IDENTITY (testAccount.ts: heartbeat id or app_metadata), never
// from the request body. For a real creator `resolveCostMode` returns the
// legacy flow with every new extra OFF, whatever the request asks for.
//
// ⚖️ PURE AND SELF-CONTAINED (no imports), so the edge copy at
// supabase/functions/_shared/realisticPanel.ts is generated byte for byte
// (scripts/ci/generate_shared_pilot_core.mjs) and node scripts can import it.
//
// ⚖️ NO SPEND HAPPENS HERE. Apify reads go through the policy-v2 guard of #1320
// (worker/src/apifyGuard.ts: per-read result limit, 30-day cache, dedupe, the
// cheapest actor, alert-not-stop for creators, hard caps for batch/test jobs).
// This module only DECIDES whether a read may be attempted and how; it never
// duplicates that guard.

export type AccountKind = 'real' | 'test' | 'panel'
export const COST_MODES = ['test', 'checkpoint', 'full'] as const
export type CostMode = (typeof COST_MODES)[number]

/** The secondary extras. Each has its own flag and its own per-run cost cap. */
export const EXTRAS = [
  'product_pages', 'pain_map', 'personas', 'outside_knowledge', 'audience_comments', 'niche_notes',
] as const
export type Extra = (typeof EXTRAS)[number]

/** Default per-run caps in USD (estimates; prices UNCONFIRMED until the AI returns). */
export const DEFAULT_EXTRA_CAPS_USD: Readonly<Record<Extra, number>> = {
  product_pages: 0.25, // Apify reads of public product pages (~$0.002/read) + AI extraction
  pain_map: 0, // hand-written or fictional map: no spend
  personas: 1.0, // practice viewers (AI calls)
  outside_knowledge: 0.3,
  audience_comments: 0.3, // her own audience first
  niche_notes: 0.2,
}

export interface CostModeDecision {
  mode: CostMode | 'live'
  /** False for a real creator: nothing in this module applies. */
  applies: boolean
  extras: Record<Extra, boolean>
}

const ALL_OFF = (): Record<Extra, boolean> => Object.fromEntries(EXTRAS.map((e) => [e, false])) as Record<Extra, boolean>

/** Parses one env-style flag; only an explicit off-word turns a default-on extra off. */
function flagOn(v: unknown, dflt: boolean): boolean {
  const s = String(v ?? '').trim().toLowerCase()
  if (s === '') return dflt
  if (['0', 'off', 'false', 'no'].includes(s)) return false
  if (['1', 'on', 'true', 'yes'].includes(s)) return true
  return dflt
}

/**
 * Which mode and extras run. `full` turns every extra on unless its own flag
 * says off (`flags[extra] = 'off'`). A real creator always gets `live` with all
 * extras off. An unknown requested mode reads as `test` (the cheap one).
 */
export function resolveCostMode(input: { account: AccountKind; requested?: unknown; flags?: Partial<Record<Extra, unknown>> }): CostModeDecision {
  if (input.account !== 'test' && input.account !== 'panel') return { mode: 'live', applies: false, extras: ALL_OFF() }
  const req = String(input.requested ?? '').trim().toLowerCase()
  const mode: CostMode = (COST_MODES as readonly string[]).includes(req) ? req as CostMode : 'test'
  const extras = ALL_OFF()
  if (mode === 'full') for (const e of EXTRAS) extras[e] = flagOn(input.flags?.[e], true)
  return { mode, applies: true, extras }
}

