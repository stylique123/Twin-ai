/**
 * Marketplace pages are NOT read until counsel agrees (§34.1). Matched on the
 * registrable host and every country variant ("amazon.co.uk", "ebay.de").
 */
export const MARKETPLACE_BLOCKLIST: readonly string[] = [
  'amazon', 'amzn', 'etsy', 'ebay', 'walmart', 'aliexpress', 'alibaba', 'temu', 'shein',
  'wish', 'target', 'bestbuy', 'mercadolibre', 'mercadolivre', 'rakuten', 'shopee',
  'lazada', 'flipkart', 'allegro', 'zalando', 'bol', 'otto', 'cdiscount', 'wayfair',
  'poshmark', 'depop', 'vinted', 'facebook', 'tiktok', 'instagram',
]

const PRIVATE_HOST = /^(localhost|.*\.local|.*\.internal|.*\.lan|(?:\d{1,3}\.){3}\d{1,3}|\[.*\])$/i
const PRIVATE_PATH = /\/(?:account|accounts|login|signin|sign-in|checkout|cart|admin|dashboard|my|orders|wp-admin|settings)(?:\/|$)/i
const SECRET_QUERY = /[?&](?:token|key|apikey|api_key|auth|session|sig|signature|password|code)=/i

/** True when the host belongs to a blocked marketplace (any TLD, any subdomain). */
export function isMarketplaceHost(host: string): boolean {
  const labels = host.toLowerCase().replace(/\.$/, '').split('.')
  return labels.some((l) => MARKETPLACE_BLOCKLIST.includes(l))
}

export type PageReadReason =
  | 'not_test_or_panel' | 'mode_not_full' | 'extra_off' | 'no_url' | 'bad_url' | 'not_https'
  | 'private_host' | 'private_path' | 'secret_in_url' | 'marketplace_until_counsel'
  | 'snapshot' | 'live_via_apify_guard' | 'no_snapshot_offline'

export interface PageReadPlan {
  read: boolean
  /** 'snapshot' = a saved fictional/public fixture offline; 'apify_policy_v2' = via #1320's guard. */
  source: 'snapshot' | 'apify_policy_v2' | 'none'
  reason: PageReadReason
  /** Always false: a failed or refused read never falls back to a name search. */
  nameSearchFallback: false
}

const refuse = (reason: PageReadReason): PageReadPlan => ({ read: false, source: 'none', reason, nameSearchFallback: false })

/**
 * Whether a fixture's product URL may be read in the realistic mode.
 * - only test/panel accounts in `full` with `product_pages` on;
 * - PUBLIC https pages only (no private host, account/checkout path, or secret in the query);
 * - marketplace domains refused until `counselMarketplaceOk` (owner flips after counsel);
 * - offline (AI/Apify paused) a saved snapshot is used; with no snapshot nothing is read;
 * - live reads are routed to the policy-v2 Apify guard, never called from here.
 */
export function planProductPageRead(input: {
  decision: CostModeDecision
  url: unknown
  offline: boolean
  hasSnapshot: boolean
  counselMarketplaceOk?: boolean
}): PageReadPlan {
  if (!input.decision.applies) return refuse('not_test_or_panel')
  if (input.decision.mode !== 'full') return refuse('mode_not_full')
  if (!input.decision.extras.product_pages) return refuse('extra_off')
  const raw = typeof input.url === 'string' ? input.url.trim() : ''
  if (!raw) return refuse('no_url')
  let u: URL
  try { u = new URL(raw) } catch { return refuse('bad_url') }
  if (u.protocol !== 'https:') return refuse('not_https')
  if (u.username || u.password || PRIVATE_HOST.test(u.hostname)) return refuse('private_host')
  if (PRIVATE_PATH.test(u.pathname)) return refuse('private_path')
  if (SECRET_QUERY.test(u.search)) return refuse('secret_in_url')
  if (isMarketplaceHost(u.hostname) && input.counselMarketplaceOk !== true) return refuse('marketplace_until_counsel')
  if (input.hasSnapshot) return { read: true, source: 'snapshot', reason: 'snapshot', nameSearchFallback: false }
  if (input.offline) return refuse('no_snapshot_offline')
  return { read: true, source: 'apify_policy_v2', reason: 'live_via_apify_guard', nameSearchFallback: false }
}

/** After a failed page read: no name search, no guess. The product keeps only what she gave. */
export function afterFailedPageRead(): { nameSearch: false; useExtracted: false } {
  return { nameSearch: false, useExtracted: false }
}

