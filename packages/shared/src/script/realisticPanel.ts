// ─── 3. PRACTICE VIEWERS (PERSONAS) ────────────────────────────────────────

export const PERSONA_MIN_CORRELATION = 0.5

/** Pearson correlation; null when undefined (fewer than 3 pairs or no variance). */
export function pearson(xs: readonly number[], ys: readonly number[]): number | null {
  const pairs = xs.map((x, i) => [x, ys[i]] as const).filter(([a, b]) => Number.isFinite(a) && Number.isFinite(b as number)) as Array<readonly [number, number]>
  const n = pairs.length
  if (n < 3) return null
  const mx = pairs.reduce((s, [a]) => s + a, 0) / n, my = pairs.reduce((s, [, b]) => s + b, 0) / n
  let sxy = 0, sxx = 0, syy = 0
  for (const [a, b] of pairs) { sxy += (a - mx) * (b - my); sxx += (a - mx) ** 2; syy += (b - my) ** 2 }
  if (sxx === 0 || syy === 0) return null
  return sxy / Math.sqrt(sxx * syy)
}

function ranks(v: readonly number[]): number[] {
  const idx = v.map((x, i) => [x, i] as const).sort((a, b) => a[0] - b[0])
  const r = new Array<number>(v.length)
  for (let i = 0; i < idx.length;) {
    let j = i
    while (j + 1 < idx.length && idx[j + 1]![0] === idx[i]![0]) j++
    for (let k = i; k <= j; k++) r[idx[k]![1]] = (i + j) / 2 + 1
    i = j + 1
  }
  return r
}

/** Spearman rank correlation (ties averaged); null as for pearson. */
export function spearman(xs: readonly number[], ys: readonly number[]): number | null {
  const pairs = xs.map((x, i) => [x, ys[i]] as const).filter(([a, b]) => Number.isFinite(a) && Number.isFinite(b as number)) as Array<readonly [number, number]>
  if (pairs.length < 3) return null
  return pearson(ranks(pairs.map((p) => p[0])), ranks(pairs.map((p) => p[1])))
}

export interface PersonaCalibration { persona: string; hook_r: number | null; craft_r: number | null; measured_at: string | null }

/**
 * A persona may influence SELECTION only when its stored calibration is at least
 * 0.5 on BOTH sets it was measured on (an unmeasured set, null, counts as below).
 * Below that its read is recorded as a signal (judge pre-score, blind package)
 * and changes nothing.
 */
export function personaMayInfluence(c: PersonaCalibration | null | undefined): boolean {
  if (!c) return false
  return [c.hook_r, c.craft_r].every((r) => typeof r === 'number' && Number.isFinite(r) && r >= PERSONA_MIN_CORRELATION)
}

export interface Candidate { id: string; honestyPassed: boolean; baseScore: number; personaScores?: Record<string, number> }

/**
 * Orders candidates. The honesty gate is FIRST and final: a candidate that
 * failed it is never selectable, whatever any persona says. Only calibrated
 * personas add to the score; the rest are carried as metadata only.
 */
export function selectWithPersonas(cands: readonly Candidate[], calib: readonly PersonaCalibration[], weight = 0.3): {
  order: string[]; blocked: string[]; influencing: string[]; signalOnly: string[]
} {
  const by = new Map(calib.map((c) => [c.persona, c]))
  const personas = [...new Set(cands.flatMap((c) => Object.keys(c.personaScores ?? {})))]
  const influencing = personas.filter((p) => personaMayInfluence(by.get(p)))
  const signalOnly = personas.filter((p) => !influencing.includes(p))
  const score = (c: Candidate) => {
    const vs = influencing.map((p) => c.personaScores?.[p]).filter((v): v is number => typeof v === 'number' && Number.isFinite(v))
    return c.baseScore + (vs.length ? weight * (vs.reduce((a, b) => a + b, 0) / vs.length) : 0)
  }
  const ok = cands.filter((c) => c.honestyPassed === true)
  return {
    order: [...ok].sort((a, b) => score(b) - score(a)).map((c) => c.id),
    blocked: cands.filter((c) => c.honestyPassed !== true).map((c) => c.id),
    influencing,
    signalOnly,
  }
}

/** The persona part of the blind package / judge pre-score: numbers and labels only. */
export function personaMetadata(scores: Record<string, number> | undefined, calib: readonly PersonaCalibration[]): Array<{ persona: string; score: number; calibrated: boolean }> {
  const by = new Map(calib.map((c) => [c.persona, c]))
  return Object.entries(scores ?? {}).filter(([, v]) => Number.isFinite(v)).map(([p, v]) => ({ persona: p, score: v, calibrated: personaMayInfluence(by.get(p)) }))
}

// ─── 4. EXTRAS LEDGER: PER-RUN CAP, COUNTS-ONLY USE REPORT ─────────────────

export class ExtrasLedger {
  private spent: Record<string, number> = {}
  private uses: Record<string, number> = {}
  private refusals: Record<string, number> = {}
  private decision: CostModeDecision
  private caps: Readonly<Record<Extra, number>>
  // Plain fields, not parameter properties: node's type stripping (scripts import this file) cannot erase those.
  constructor(decision: CostModeDecision, caps: Readonly<Record<Extra, number>> = DEFAULT_EXTRA_CAPS_USD) {
    this.decision = decision
    this.caps = caps
  }
  /** Reserve spend for one use. False (and counted) when the extra is off or the cap would be passed. */
  charge(extra: Extra, usd: number): boolean {
    if (!this.decision.applies || !this.decision.extras[extra]) { this.refusals[extra] = (this.refusals[extra] ?? 0) + 1; return false }
    const next = (this.spent[extra] ?? 0) + Math.max(0, usd)
    if (next > this.caps[extra] + 1e-9) { this.refusals[extra] = (this.refusals[extra] ?? 0) + 1; return false }
    this.spent[extra] = next
    this.uses[extra] = (this.uses[extra] ?? 0) + 1
    return true
  }
  /** Counts and dollars only — no text, no ids, no URLs. */
  report(): Record<Extra, { on: boolean; uses: number; refused: number; usd: number; cap_usd: number }> {
    return Object.fromEntries(EXTRAS.map((e) => [e, {
      on: this.decision.applies && this.decision.extras[e],
      uses: this.uses[e] ?? 0,
      refused: this.refusals[e] ?? 0,
      usd: Math.round((this.spent[e] ?? 0) * 10000) / 10000,
      cap_usd: this.caps[e],
    }])) as Record<Extra, { on: boolean; uses: number; refused: number; usd: number; cap_usd: number }>
  }
}

// ─── 5. GUARDRAILS: BUDGET BEFORE THE RUN, DOLLARS BY CALLER AND MODEL ─────

/** Unit costs (USD) for the pre-run estimate. UNCONFIRMED until prices are re-read. */
export const UNIT_COST_USD = {
  script_ai: 0.06, // writer + editor + gates per request (panel history, UNCONFIRMED)
  page_read_apify: 0.002, // one public page, cheapest actor, result limit 1
  page_extract_ai: 0.004,
  persona_read_ai: 0.003, // per persona per script
  outside_knowledge_ai: 0.004,
  audience_comments_ai: 0.003,
  niche_notes_ai: 0.002,
} as const

export interface BudgetLine { provider: 'apify' | 'gemini'; caller: string; usd: number }
export interface PanelBudget { lines: BudgetLine[]; apify_usd: number; ai_usd: number; total_usd: number }

/** The per-panel budget printed before the run. */
export function estimatePanelBudget(input: { decision: CostModeDecision; requests: number; pageReads: number; personas: number }): PanelBudget {
  const d = input.decision, n = Math.max(0, input.requests), U = UNIT_COST_USD
  const lines: BudgetLine[] = [{ provider: 'gemini', caller: 'script', usd: n * U.script_ai }]
  if (d.applies && d.mode === 'full') {
    if (d.extras.product_pages) {
      lines.push({ provider: 'apify', caller: 'product_pages', usd: input.pageReads * U.page_read_apify })
      lines.push({ provider: 'gemini', caller: 'product_pages', usd: input.pageReads * U.page_extract_ai })
    }
    if (d.extras.personas) lines.push({ provider: 'gemini', caller: 'personas', usd: n * input.personas * U.persona_read_ai })
    if (d.extras.outside_knowledge) lines.push({ provider: 'gemini', caller: 'outside_knowledge', usd: n * U.outside_knowledge_ai })
    if (d.extras.audience_comments) lines.push({ provider: 'gemini', caller: 'audience_comments', usd: n * U.audience_comments_ai })
    if (d.extras.niche_notes) lines.push({ provider: 'gemini', caller: 'niche_notes', usd: n * U.niche_notes_ai })
  }
  const r = (x: number) => Math.round(x * 10000) / 10000
  for (const l of lines) l.usd = r(l.usd)
  const apify = r(lines.filter((l) => l.provider === 'apify').reduce((a, l) => a + l.usd, 0))
  const ai = r(lines.filter((l) => l.provider === 'gemini').reduce((a, l) => a + l.usd, 0))
  return { lines, apify_usd: apify, ai_usd: ai, total_usd: r(apify + ai) }
}

/** Refuse to start when the estimate passes the cap (or the cap is missing/invalid). */
export function budgetGate(b: PanelBudget, capUsd: unknown): { ok: boolean; reason: 'within_cap' | 'over_cap' | 'no_cap' } {
  const cap = Number(capUsd)
  if (!Number.isFinite(cap) || cap <= 0) return { ok: false, reason: 'no_cap' }
  return b.total_usd <= cap ? { ok: true, reason: 'within_cap' } : { ok: false, reason: 'over_cap' }
}

/**
 * Dollars by provider, caller and model for the run report, from cost rows
 * (Gemini: ai_cost_by_stage_script stage/model/est_usd; Apify: #1320's
 * apify_spend_ledger feature/actor/reserved_usd). Numbers and labels only.
 */
export function costByCallerAndModel(rows: ReadonlyArray<{ provider: string; caller?: unknown; model?: unknown; usd?: unknown }>): Array<{ provider: string; caller: string; model: string; usd: number; rows: number }> {
  const m = new Map<string, { provider: string; caller: string; model: string; usd: number; rows: number }>()
  const label = (v: unknown) => String(v ?? 'unknown').replace(/[^\w.:/-]/g, '').slice(0, 64) || 'unknown'
  for (const r of rows) {
    const k = `${label(r.provider)}|${label(r.caller)}|${label(r.model)}`
    const e = m.get(k) ?? { provider: label(r.provider), caller: label(r.caller), model: label(r.model), usd: 0, rows: 0 }
    const u = Number(r.usd)
    e.usd += Number.isFinite(u) ? u : 0
    e.rows++
    m.set(k, e)
  }
  return [...m.values()].map((e) => ({ ...e, usd: Math.round(e.usd * 100000) / 100000 })).sort((a, b) => b.usd - a.usd)
}
